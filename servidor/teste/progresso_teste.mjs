// confere o pagamento da progressão no servidor: missão do dia certa paga 1×, missão de outro dia não, teto de 3/dia,
// nível paga 1×, conquista paga 1× e dá título, sequência de dias no presente
import { readFileSync } from "node:fs";
const U = process.argv[2] || "http://127.0.0.1:8787";
const D = JSON.parse(readFileSync(new URL("../src/dados.js", import.meta.url), "utf8").replace(/^[\s\S]*?export default /, "").replace(/;\s*$/, ""));
let falhas = 0; const ok = (c, m) => { console.log((c ? "OK      " : "FALHOU  ") + m); if (!c) falhas++; };
const r0 = await (await fetch(U + "/v1/conta", { method: "POST", body: "{}" })).json();
const A = `KDX ${r0.id}:${r0.segredo}`;
const op = async (d) => (await (await fetch(U + "/v1/op", { method: "POST", headers: { authorization: A }, body: JSON.stringify(d) })).json());
const saude = await (await fetch(U + "/v1/saude")).json();
const hoje = saude.dia, semana = Math.floor((hoje + 3) / 7);
function sorteio(semente, n, tam) { let s = (semente * 7919 + 17) % 2147483647; if (s <= 0) s += 2147483646; const out = [];
  while (out.length < Math.min(n, tam)) { s = (s * 48271) % 2147483647; const i = s % tam; if (!out.includes(i)) out.push(i); } return out; }
const doDia = sorteio(hoje, 4, D.prog.diarias.length).map((i) => D.prog.diarias[i]);
const fora = D.prog.diarias.find((m) => !doDia.includes(m));
let r = await op({ tipo: "progresso", k: "missao", id: doDia[0].id, dia: hoje });
ok(r.resultado.moedas === (doDia[0].moedas | 0) && (r.resultado.booster | 0) === (doDia[0].booster | 0), `missão do dia paga (${doDia[0].id}: ${r.resultado.moedas})`);
r = await op({ tipo: "progresso", k: "missao", id: doDia[0].id, dia: hoje });
ok(r.resultado.repetido, "a mesma missão não paga 2×");
r = await op({ tipo: "progresso", k: "missao", id: fora.id, dia: hoje });
ok(r.resultado.erro, "missão que não é do dia é recusada");
r = await op({ tipo: "progresso", k: "missao", id: doDia[1].id, dia: hoje });
ok(r.resultado.moedas === 0 && r.resultado.essencia === Math.round(doDia[1].moedas / 2), `2ª missão do dia paga Essência (${r.resultado.essencia})`);
r = await op({ tipo: "progresso", k: "missao", id: doDia[2].id, dia: hoje });
ok(r.resultado.koins === Math.round(doDia[2].moedas / 2), `3ª missão do dia paga Koins (${r.resultado.koins})`);
r = await op({ tipo: "progresso", k: "missao", id: doDia[3].id, dia: hoje });
ok(r.resultado.repetido, "a 4ª (troca) não passa do teto de 3 por dia");
const sem = sorteio(semana + 100000, 3, D.prog.semanais.length).map((i) => D.prog.semanais[i]);
r = await op({ tipo: "progresso", k: "semanal", id: sem[0].id, semana });
ok(!r.resultado.erro && !r.resultado.repetido, "semanal da semana paga");
r = await op({ tipo: "progresso", k: "nivel", nivel: 5 });
ok(r.resultado.booster === 1 && r.resultado.essencia === 100 && r.resultado.titulo === "iniciado", "nível 5: booster, 100 Essência e título Iniciado");
r = await op({ tipo: "progresso", k: "nivel", nivel: 5 });
ok(r.resultado.repetido, "nível não paga 2×");
r = await op({ tipo: "progresso", k: "conquista", id: "vitorias_100" });
ok(r.resultado.moedas === 200 && r.resultado.titulo === "veterano" && r.perfil.titulos.includes("veterano"), "conquista com título");
r = await op({ tipo: "progresso", k: "maestria", trad: "taoismo", nivel: 5 });
ok(r.resultado.titulo === "mestre_taoismo", "maestria 5 dá Mestre do Taoísmo");
r = await op({ tipo: "resgatar" });
ok(r.resultado.seq === 1 && r.perfil.resgates.max === 1, "presente: 1º dia seguido");
ok(r.resultado.cal?.dia === 1 && r.resultado.cal.premio.moedas === 30 && r.perfil.cal.n === 1, "presente marca o dia 1 do calendário (+30 moedas)");
r = await op({ tipo: "resgatar" });
ok(!r.resultado.cal && r.perfil.cal.n === 1, "o mesmo dia não marca 2×");
r = await op({ tipo: "progresso", k: "nivel", nivel: 10 });
ok(r.resultado.booster === 1 && r.resultado.koins === 30 && r.resultado.escolha === "R" && r.perfil.escolhas.includes("R"), "nível 10: booster, 30 Koins e escolha de carta R");
r = await op({ tipo: "progresso", k: "nivel", nivel: 15 });
ok(r.resultado.moedas === 200 && r.resultado.titulo === "teurgo", "nível 15: 200 moedas e título Teurgo");
r = await op({ tipo: "progresso", k: "maestria", trad: "taoismo", nivel: 6 });
ok(r.resultado.booster_trad === 1 && r.perfil.boosters_trad === 1, "maestria 6: booster de tradição");
r = await op({ tipo: "progresso", k: "maestria", trad: "taoismo", nivel: 7 });
ok(r.perfil.emotes?.includes("taoismo_0") && r.perfil.emotes.includes("taoismo_1"), "maestria 7: 2 emotes do Taoísmo");
r = await op({ tipo: "progresso", k: "maestria", trad: "taoismo", nivel: 10 });
ok(r.resultado.booster_trad === 2 && r.resultado.titulo === "arauto_taoismo", "maestria 10: 2 boosters de tradição e Arauto do Caminho");
r = await op({ tipo: "booster", de_trad: true, pacote: "taoismo" });
ok(r.resultado.cartas?.length === 3 && r.resultado.cartas.every((e) => D.cartas[e.id].c === "taoismo") && r.perfil.boosters_trad === 2,
  "booster de tradição: as 3 cartas do Taoísmo, sobra 2");
r = await op({ tipo: "booster", de_trad: true, pacote: "abismo" });
ok(r.resultado.erro === "tradição inválida", "booster de tradição do Abismo é recusado");
const moedasAntes = r.perfil.moedas;
r = await op({ tipo: "escolha_abrir" });
const opc = r.resultado.opcoes || [];
const rar = (cid) => (D.cartas[cid].l ? "SR" : D.cartas[cid].u <= 3 ? "C" : "R");
ok(opc.length === 3 && new Set(opc).size === 3 && opc.every((c) => rar(c) === "R"), "escolha de carta: 3 cartas R diferentes");
r = await op({ tipo: "escolha_abrir" });
ok(JSON.stringify(r.resultado.opcoes) === JSON.stringify(opc), "abrir de novo mostra as mesmas 3 (não sorteia de novo)");
const antes = r.perfil.colecao[opc[1]] | 0;
r = await op({ tipo: "escolha_pegar", carta: opc[1] });
ok(r.resultado.carta === opc[1] && (r.perfil.colecao[opc[1]] | 0) === antes + 1 && !r.perfil.escolha_aberta && r.perfil.moedas === moedasAntes,
  "pegar 1 das 3: entra na coleção e a escolha fecha");
r = await op({ tipo: "escolha_pegar", carta: opc[0] });
ok(r.resultado.erro, "não dá para pegar outra depois");
r = await op({ tipo: "escolha_abrir" });
ok(r.resultado.erro === "sem escolha de carta", "sem escolha guardada: recusa");
console.log(falhas ? `---- ${falhas} FALHA(S)` : "---- PROGRESSO OK");
